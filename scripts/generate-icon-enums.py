"""Generate family enums from Font Awesome's public metadata (no SVGs or token).

python scripts/generate-icon-enums.py --version 7.3.1
python scripts/generate-icon-enums.py --catalog scripts/icon-catalog.json --check
"""
import argparse
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src/main/java/com/jwebmp/plugins/fontawesome5pro"
KEYWORDS = set("abstract assert boolean break byte case catch char class const continue default do double else enum extends final finally float for goto if implements import instanceof int interface long native new package private protected public return short static strictfp super switch synchronized this throw throws transient try void volatile while true false null _".split())


def query(text):
    request = urllib.request.Request(
        "https://api.fontawesome.com", json.dumps({"query": text}).encode(),
        {"Content-Type": "application/json", "User-Agent": "Mozilla/5.0 JWebMP-Catalog-Generator"})
    with urllib.request.urlopen(request, timeout=60) as response:
        data = json.load(response)
    if data.get("errors"):
        raise ValueError(data["errors"])
    return data["data"]["release"]


def download(version):
    version = query(' { release(version: ' + json.dumps(version) + ') { version } }')['version']
    icons = []
    page = 1
    while True:
        data = query('{ release(version: ' + json.dumps(version) + ') { iconsPaginated(page: '
                     + str(page) + ', pageSize: 500) { totalIconCount totalPageCount icons { id '
                     'familyStylesByLicense { pro { family style } } } } } }')['iconsPaginated']
        icons.extend(data['icons'])
        if page == data['totalPageCount']:
            break
        page += 1
    if len(icons) != data['totalIconCount'] or len({i['id'] for i in icons}) != len(icons):
        raise ValueError("Incomplete or duplicate icon metadata")
    return {"version": version, "icons": icons}


def compact(data):
    families = {}
    for icon in data['icons']:
        for pair in icon['familyStylesByLicense']['pro']:
            if pair['style'] == 'brands':
                continue
            families.setdefault(pair['family'], {}).setdefault(pair['style'], []).append(icon['id'])
    return {"version": data['version'], "source": "https://api.fontawesome.com",
            "families": {f: {s: sorted(set(names)) for s, names in sorted(styles.items())}
                         for f, styles in sorted(families.items())}}


def generate(catalog):
    outputs = {}
    for family, styles in catalog['families'].items():
        # Sharing a family enum is safe only when every style has exactly the same names.
        names = next(iter(styles.values()))
        if not names or any(v != names for v in styles.values()):
            raise ValueError(f"{family}: style membership differs; generate separate style enums")
        identifiers = [('$' if n[0].isdigit() or n in KEYWORDS else '') + n.replace('-', '_') for n in names]
        if len(set(identifiers)) != len(identifiers) or any(not re.fullmatch(r'[$a-zA-Z_][$a-zA-Z_0-9]*', n) for n in identifiers):
            raise ValueError(f"{family}: invalid or colliding Java identifiers")
        title = ''.join(p.title() for p in family.split('-'))
        family_constant = '_'.join(p.title() for p in family.split('-'))
        class_name = f'FontAwesome{title}Icons'
        default = 'solid' if 'solid' in styles else next(iter(styles))
        variants = ', '.join('IconVariant.' + s.title() for s in styles)
        body = ',\n'.join('    ' + n for n in identifiers) + ';'
        outputs[PACKAGE / (class_name + '.java')] = f'''package com.jwebmp.plugins.fontawesome5pro;

import com.jwebmp.plugins.fontawesome5.options.IconFamily;
import com.jwebmp.plugins.fontawesome5.options.IconVariant;
import java.util.Set;

/**
 * {family} icons available in Font Awesome {catalog['version']} ({len(names)} canonical names).
 * Generated by scripts/generate-icon-enums.py from public Font Awesome metadata.
 * Requires the corresponding licensed assets or Kit; aliases are deliberately omitted.
 */
public enum {class_name} implements IFontAwesomeFamilyIcon
{{
{body}

    private static final Set<IconVariant> VARIANTS = Set.of({variants});

    @Override
    public IconFamily getFamily() {{ return IconFamily.{family_constant}; }}

    @Override
    public IconVariant getVariant() {{ return IconVariant.{default.title()}; }}

    @Override
    public Set<IconVariant> getSupportedVariants() {{ return VARIANTS; }}

    @Override
    public String toString() {{ return "fa-" + toAngularIconAttributeName(); }}
}}
'''
    # The legacy enum is already close to javac's per-method bytecode limit.
    # New names are inherited as typed fields, so existing enum constants,
    # ordinals and compiled references remain intact.
    legacy = PACKAGE / 'FontAwesome5ProIcons.java'
    legacy_source = legacy.read_text(encoding='utf-8')
    legacy_constants = set(re.findall(r'^\s*([$\w]+)\s*,', legacy_source, re.M))
    current = catalog['families']['classic']['solid']
    missing = [('$' if n[0].isdigit() or n in KEYWORDS else '') + n.replace('-', '_')
               for n in current if ('$' if n[0].isdigit() or n in KEYWORDS else '') + n.replace('-', '_') not in legacy_constants]
    fields = '\n'.join(f'    FontAwesomeClassicIcons {name} = FontAwesomeClassicIcons.{name};' for name in missing)
    outputs[PACKAGE / 'FontAwesome5ProAdditionalIcons.java'] = f'''package com.jwebmp.plugins.fontawesome5pro;

/**
 * {len(missing)} canonical Pro names added after the legacy FontAwesome5ProIcons enum.
 * Generated from Font Awesome {catalog['version']} metadata. These inherited fields
 * preserve source access through FontAwesome5ProIcons without changing the legacy
 * enum's constants, ordinals or binary field references. The field type is
 * FontAwesomeClassicIcons, so they are not in FontAwesome5ProIcons.values().
 */
public interface FontAwesome5ProAdditionalIcons
{{
{fields}
}}
'''
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--version', default='7.3.1')
    parser.add_argument('--catalog', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalog = json.loads(args.catalog.read_text(encoding='utf-8')) if args.catalog else compact(download(args.version))
    if 'icons' in catalog:
        catalog = compact(catalog)
    outputs = generate(catalog)
    outputs[ROOT / 'scripts/icon-catalog.json'] = json.dumps(catalog, indent=2) + '\n'
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                raise SystemExit(f'Generated file differs: {path}')
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
    print(f"{'Checked' if args.check else 'Generated'} {len(outputs)-2} family enums and legacy Pro additions for Font Awesome {catalog['version']}")


if __name__ == '__main__':
    main()
